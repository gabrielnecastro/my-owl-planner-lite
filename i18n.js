  const DICTS = { pt, en, es };
  let lang = 'pt';

  /** Idioma do sistema → pt / es / en (padrão: en). */
  function fromSystem(locale) {
    const l = String(locale || '').toLowerCase();
    if (l.startsWith('pt')) return 'pt';
    if (l.startsWith('es')) return 'es';
    return 'en';
  }

  function setLang(l) { lang = DICTS[l] ? l : 'pt'; }
  function getLang() { return lang; }
  function locale() { return LOCALES[lang]; }

  function t(key, vars) {
    let s = DICTS[lang][key] ?? pt[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    return s;
  }
  function tn(key, n, vars = {}) {
    const form = new Intl.PluralRules(LOCALES[lang]).select(n) === 'one' ? 'one' : 'other';
    return t(`${key}_${form}`, { n, ...vars });
  }

  /** Aplica traduções em elementos com data-i18n / data-i18n-ph / data-i18n-title. */
  function apply(rootEl) {
    if (!rootEl) return;
    rootEl.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    rootEl.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    rootEl.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    rootEl.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    if (rootEl.documentElement) rootEl.documentElement.lang = LOCALES[lang];
  }

  /** Nomes padrão das categorias em todos os idiomas (para traduzir só as que não foram renomeadas). */
  const DEFAULT_CAT_NAMES = Object.fromEntries(['trabalho', 'freela', 'estudo', 'pessoal']
    .map((id) => [id, Object.values(DICTS).map((d) => d[`catdef.${id}`])]));

  const api = { t, tn, setLang, getLang, locale, apply, fromSystem, LANG_NAMES, LOCALES, DEFAULT_CAT_NAMES, DICTS };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.I18n = api;
